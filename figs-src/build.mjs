// Builds every figure into figs/<id>.js (lazy-loaded SVG) and writes figs/index.js (titles, parts and readouts,
// localized with tr) plus the English and Spanish strings into lang/*.js.
// Usage: node figs-src/build.mjs [id ...] [--audit]
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { makeFig } from "./lib.mjs";
import { ISO_CSS } from "./kit/iso-kit.mjs";
import { STEPS } from "./steps.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const only = process.argv.slice(2).filter((a) => !a.startsWith("--"));
const files = readdirSync(join(HERE, "figures")).filter((f) => f.endsWith(".mjs")).sort();
const metas = [];
let failing = 0;
for (const file of files) {
  const mod = await import(pathToFileURL(join(HERE, "figures", file)).href);
  const m0 = mod.meta; if (!m0.steps && STEPS[m0.id]) m0.steps = STEPS[m0.id];
  // pins and chips are numbered in the order the process visits them
  if (m0.steps) { const first = (id) => { const i = m0.steps.findIndex((st) => st.node === id || (!st.node && (st.flow || []).some((f) => f.split(':')[0] === id))); return i < 0 ? 99 : i; }; m0.nodes = m0.nodes.map((n, i) => [n, i]).sort((x, y) => first(x[0].id) - first(y[0].id) || x[1] - y[1]).map((x) => x[0]); }
  for (const st of m0.steps || []) if (st.node && !m0.nodes.some((n) => n.id === st.node)) throw new Error(`${m0.id}: step node ${st.node} is not a part`);
  metas.push(m0);
  if (only.length && !only.includes(mod.spec.id)) continue;
  const out = makeFig(mod.spec, mod.build);
  const js = `(window.FIGD=window.FIGD||{})[${JSON.stringify(out.id)}]=${JSON.stringify({ w: out.w, h: out.h, st: out.stagger, svg: out.svg })};\n`;
  writeFileSync(join(ROOT, "figs", out.id + ".js"), js);
  console.log(`${out.id}: ${out.items} items, ${(js.length / 1024).toFixed(0)} KB, settle ${(out.ms / 1000).toFixed(1)} s`);
  if (out.report) { writeFileSync(join(HERE, "out-" + out.id + ".audit.txt"), out.report); const tail = out.report.split("\n").filter((l) => /problem|unsupported|failing|passed|pairs|items whose/.test(l) && !/\b0 (problems|pairs|unsupported|items)/.test(l)); console.log(tail.join("\n")); failing += +(out.report.match(/(\d+) failing/) || [0, 0])[1]; }
}

// index + translations from the metas (Russian is the source language, as in the rest of the app)
const S = (o) => `tr(${JSON.stringify(o.ru)})`;
const idx = metas.map((m) => `${JSON.stringify(m.id)}:{t:${JSON.stringify(m.topic)},title:${S(m.title)},cap:${S(m.cap)},ex:${m.explode ? 1 : 0},nodes:[${m.nodes.map((n) => `[${JSON.stringify(n.id)},${S(n.name)},${S(n.read)},${n.kw ? `new RegExp(${JSON.stringify(n.kw)},"i")` : "null"}]`).join(",")}],steps:[${(m.steps || []).map((st) => `[${JSON.stringify(st.node || "")},${st.ex === undefined ? -1 : st.ex ? 1 : 0},${JSON.stringify(st.flow || [])},${S(st.t)}]`).join(",")}]}`);
writeFileSync(join(ROOT, "figs", "index.js"), `// Generated by figs-src/build.mjs. Figures are loaded on demand from figs/<id>.js.\nconst FIGS={${idx.join(",\n")}};\nconst FIG_OF=Object.fromEntries(Object.entries(FIGS).map(([id,f])=>[f.t,id]));\n`);

writeFileSync(join(ROOT, "figs", "view.css"), "/* anatomy kit styles (MIT, github.com/wheresryan22/anatomy) + viewer */\n" + ISO_CSS.trim() + "\n" + readFileSync(join(HERE, "view.css"), "utf8"));
const UI = JSON.parse(readFileSync(join(HERE, "ui-strings.json"), "utf8"));
for (const lang of ["en", "es"]) {
  const pairs = new Map();
  for (const m of metas) for (const o of [m.title, m.cap, ...m.nodes.flatMap((n) => [n.name, n.read]), ...(m.steps || []).map((st) => st.t)]) { if (!o[lang]) throw new Error(`${m.id}: missing ${lang} for ${o.ru}`); pairs.set(o.ru, o[lang]); }
  for (const o of UI) pairs.set(o.ru, o[lang]);
  const block = `// BEGIN FIGS (generated by figs-src/build.mjs)\nObject.assign(DICT, {\n${[...pairs].map(([a, b]) => `${JSON.stringify(a)}: ${JSON.stringify(b)},`).join("\n")}\n});\n// END FIGS\n`;
  const path = join(ROOT, "lang", lang + ".js");
  let src = readFileSync(path, "utf8");
  src = src.includes("// BEGIN FIGS") ? src.replace(/\/\/ BEGIN FIGS[\s\S]*\/\/ END FIGS\n/, block) : src + "\n" + block;
  writeFileSync(path, src);
}
console.log(`index: ${metas.length} figures${process.argv.includes("--audit") ? `, ${failing} failing audit lines` : ""}`);
if (failing) process.exitCode = 1;
